        return pokemon.m.species;
    }

    pub fn setSpecies(pokemon: *StaticPokemon, s: u16) void {
        pokemon.m.species = s;
    }

    pub fn level(pokemon: StaticPokemon) u8 {
        return pokemon.m.level;
    }

    pub fn setLevel(pokemon: *StaticPokemon, l: u8) void {
        pokemon.m.level = l;
    }
};

